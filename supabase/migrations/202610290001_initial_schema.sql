create table if not exists public.competitions (
  id bigint generated by default as identity primary key,
  provider text not null default 'api-football',
  provider_id bigint,
  name text not null,
  country text not null default 'Italy',
  code text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(provider, provider_id)
);
create table if not exists public.seasons (
  id bigint generated by default as identity primary key,
  competition_id bigint not null references public.competitions(id) on delete cascade,
  provider_season_id bigint,
  year integer not null,
  start_date date,
  end_date date,
  current boolean not null default false,
  unique(competition_id, year)
);
create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  provider text not null default 'api-football',
  provider_id bigint not null,
  name text not null,
  short_name text,
  logo_url text,
  country text,
  created_at timestamptz not null default now(),
  unique(provider, provider_id)
);
create table if not exists public.fixtures (
  id bigint generated by default as identity primary key,
  provider text not null default 'api-football',
  provider_id bigint not null,
  season_id bigint references public.seasons(id) on delete set null,
  home_team_id bigint not null references public.teams(id),
  away_team_id bigint not null references public.teams(id),
  kickoff_at timestamptz not null,
  status text not null default 'scheduled',
  elapsed_minute integer,
  home_goals integer,
  away_goals integer,
  venue text,
  referee text,
  last_synced_at timestamptz,
  created_at timestamptz not null default now(),
  unique(provider, provider_id),
  check (home_team_id <> away_team_id)
);
create table if not exists public.team_match_stats (
  id bigint generated by default as identity primary key,
  fixture_id bigint not null references public.fixtures(id) on delete cascade,
  team_id bigint not null references public.teams(id) on delete cascade,
  is_home boolean not null,
  goals integer,
  corners integer,
  shots integer,
  shots_on_target integer,
  possession numeric(5,2),
  yellow_cards integer,
  red_cards integer,
  stats_json jsonb not null default '{}'::jsonb,
  collected_at timestamptz,
  unique(fixture_id, team_id)
);
create table if not exists public.predictions (
  id bigint generated by default as identity primary key,
  fixture_id bigint not null references public.fixtures(id) on delete cascade,
  market text not null check (market in ('goals_total','corners_total','home_corners','away_corners')),
  line numeric(5,2),
  selection text not null check (selection in ('over','under','expected_value','home','draw','away')),
  probability numeric(5,2) check (probability between 0 and 100),
  expected_total numeric(6,2),
  confidence text check (confidence in ('low','medium','high')),
  model_version text not null default 'v1',
  is_live boolean not null default false,
  inputs_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.odds_snapshots (
  id bigint generated by default as identity primary key,
  fixture_id bigint not null references public.fixtures(id) on delete cascade,
  provider text not null,
  bookmaker text not null,
  market text not null check (market in ('goals_total','corners_total','home_corners','away_corners')),
  line numeric(5,2),
  selection text not null check (selection in ('over','under')),
  odds numeric(8,3) not null check (odds > 1),
  is_live boolean not null default false,
  captured_at timestamptz not null default now()
);
create index if not exists idx_seasons_competition_year on public.seasons(competition_id, year desc);
create index if not exists idx_fixtures_kickoff on public.fixtures(kickoff_at);
create index if not exists idx_fixtures_season_status on public.fixtures(season_id, status);
create index if not exists idx_team_match_stats_team_fixture on public.team_match_stats(team_id, fixture_id);
create index if not exists idx_predictions_fixture_created on public.predictions(fixture_id, created_at desc);
create index if not exists idx_odds_fixture_market_time on public.odds_snapshots(fixture_id, market, captured_at desc);

